"""Regenerate the bundled Vulkan 1.0 SPIR-V header from its GLSL sources.
Set GLSLANG to glslang/glslangValidator, or pass --glslang. --check verifies
reproducibility without changing any source. A normal APK build uses the header.
"""
from pathlib import Path
import argparse, os, struct, subprocess, tempfile

parser=argparse.ArgumentParser()
parser.add_argument('--glslang',default=os.environ.get('GLSLANG','glslangValidator'))
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
folder=Path(__file__).resolve().parents[1]/'app/src/main/cpp/vulkan'
header=['// Generated by tools/compile_vulkan_shaders.py; retain the GLSL sources.',
        '#pragma once','#include <stdint.h>']
with tempfile.TemporaryDirectory(prefix='seedless-spirv-') as temp:
    for stage in ('vert','frag'):
        binary=Path(temp)/('presenter.'+stage+'.spv')
        subprocess.run([args.glslang,'-V','--target-env','vulkan1.0','-o',str(binary),
                        str(folder/('presenter.'+stage))],check=True,capture_output=True)
        words=struct.unpack('<'+'I'*(binary.stat().st_size//4),binary.read_bytes())
        assert words[0]==0x07230203
        header.append('static const uint32_t presenter_'+stage+'[] = {\n'+',\n'.join(
            '    '+', '.join(f'0x{x:08x}u' for x in words[i:i+8]) for i in range(0,len(words),8))+'\n};')
text='\n'.join(header)+'\n'
target=folder/'presenter_shaders.h'
if args.check:
    assert target.read_text(encoding='utf8')==text, 'SPIR-V header differs from compiler output'
    print('Vulkan 1.0 shaders compile; bundled SPIR-V matches both GLSL sources')
else:
    target.write_text(text,encoding='utf8')
    print(target)
